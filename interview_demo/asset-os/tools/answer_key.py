"""Expected results for the September close data pack, used as a regression test.

This applies the same rules as the app's JavaScript checks, written a second time in Python.
It proves the checks still find what they found. It is not an independent measure of accuracy:
a rule that is wrong in one is wrong in both. It does not cover the split check.
Usage: python3 tools/answer_key.py path/to/data_pack.xlsx > js/answer-key.js
"""
import json, re, sys, statistics, collections
import openpyxl

wb = openpyxl.load_workbook(sys.argv[1], data_only=True)
sheet = lambda p: next(wb[n] for n in wb.sheetnames if n.startswith(p))
rows = lambda p: [r for r in sheet(p).iter_rows(min_row=2, values_only=True) if r[0] is not None]
props = {r[0]: r for r in rows("B0")}
cat = {str(r[0]): r[2] for r in rows("B1")}
inv = rows("B2")

key = collections.defaultdict(list)

# Duplicates: same vendor and amount, invoice numbers equal once "INV-" and punctuation are ignored.
seen = {}
for r in inv:
    k = (r[2], round(r[7], 2), re.sub(r"\D", "", str(r[1])))
    if k in seen:
        key["duplicate"].append(r[0])
    else:
        seen[k] = r[0]

# Charges to properties that were off-boarded before September.
key["offboarded"] = [r[0] for r in inv if str(props[r[3]][6]).startswith("Off-boarded")]

# Coding: the description says one thing, the GL code another (judged by eye, then confirmed).
usual = {}
for d in {r[6] for r in inv}:
    codes = collections.Counter(str(r[5]) for r in inv if r[6] == d)
    usual[d] = codes.most_common(1)[0][0]
key["miscoded"] = [r[0] for r in inv if str(r[5]) != usual[r[6]]]

# Prior period: invoice dated in August, sitting in the September register.
key["prior_period"] = [r[0] for r in inv if r[8].month == 8]

# Policy: over $10,000 and not yet approved.
key["approval"] = [r[0] for r in inv if r[7] > 10000 and r[10] != "Approved"]

# One-off amounts far above what the vendor usually bills.
by_vendor = collections.defaultdict(list)
for r in inv:
    by_vendor[r[2]].append(r[7])
key["outlier"] = [r[0] for r in inv
                  if r[7] >= 10000 and r[7] >= 5 * statistics.median(by_vendor[r[2]])]

# Budget lines more than 10% off budget.
key["variance"] = [f"{r[0]}|{r[3]}" for r in rows("B3") if abs(r[5] - r[4]) / r[4] > 0.10]

out = {k: sorted(v) if k != "variance" else v for k, v in key.items()}
print("// Generated by tools/answer_key.py from the data pack. Do not edit by hand.")
print("window.ANSWER_KEY = " + json.dumps(out, indent=1) + ";")
for k, v in out.items():
    print(f"// {k}: {len(v)}", file=sys.stderr)
