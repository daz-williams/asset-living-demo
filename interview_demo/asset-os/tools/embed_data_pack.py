"""Embed the data pack in js/data-pack.js so index.html opens with no server and no upload.
Usage: python3 tools/embed_data_pack.py "data/Asset_Living_Build_Exercise_-_Data_Pack.xlsx"
"""
import base64, json, os, sys
path = sys.argv[1]
with open(path, "rb") as f:
    b64 = base64.b64encode(f.read()).decode()
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "js", "data-pack.js"), "w") as f:
    f.write("// Generated by tools/embed_data_pack.py: the Build Exercise data pack, unchanged, as base64.\n")
    f.write("window.DATA_PACK = " + json.dumps({"name": os.path.basename(path), "base64": b64}) + ";\n")
print("Embedded", os.path.basename(path), len(b64), "chars")
